const guardConfigFileName = "gateway_guard_config.json"

type buildAsset struct {
	name string
	path string
}

// commitTempFile prefers an atomic rename. Some Windows sandboxed filesystems
// deny MoveFileEx even within the same directory, so it falls back to a copy
// and restores the previous destination if that copy fails.
func commitTempFile(tempPath, path string) error {
	if err := os.Rename(tempPath, path); err == nil {
		return nil
	} else if runtime.GOOS != "windows" {
		return err
	} else {
		renameErr := err
		var (
			oldData []byte
			oldMode os.FileMode = 0o644
			hadOld  bool
		)
		if info, statErr := os.Stat(path); statErr == nil {
			if !info.Mode().IsRegular() {
				return renameErr
			}
			oldMode = info.Mode().Perm()
			oldData, err = os.ReadFile(path)
			if err != nil {
				return errors.Join(renameErr, err)
			}
			hadOld = true
			if err := os.Remove(path); err != nil {
				return errors.Join(renameErr, err)
			}
		} else if !errors.Is(statErr, os.ErrNotExist) {
			return errors.Join(renameErr, statErr)
		}

		src, openErr := os.Open(tempPath)
		if openErr != nil {
			if hadOld {
				_ = os.WriteFile(path, oldData, oldMode)
			}
			return errors.Join(renameErr, openErr)
		}
		defer src.Close()

		dst, createErr := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, oldMode)
		if createErr != nil {
			if hadOld {
				_ = os.WriteFile(path, oldData, oldMode)
			}
			return errors.Join(renameErr, createErr)
		}
		_, copyErr := io.Copy(dst, src)
		closeErr := dst.Close()
		if copyErr != nil || closeErr != nil {
			_ = os.Remove(path)
			if hadOld {
				restoreErr := os.WriteFile(path, oldData, oldMode)
				return errors.Join(renameErr, copyErr, closeErr, restoreErr)
			}
			return errors.Join(renameErr, copyErr, closeErr)
		}
		_ = os.Remove(tempPath)
		return nil
	}
}

// guardBuildMu serializes "Build now" so two admins cannot write the same release ZIP at once.
var guardBuildMu sync.Mutex

// freshGuardConfig re-derives the server-specific Guard config fields from the running
// server's environment (the same .env values sync_config_from_env.py uses), keeping any
// other fields from the shipped config.
func freshGuardConfig() ([]byte, error) {
	cfg := map[string]any{}
	if p, ok := findFirstExisting(browserAISetupCandidates()[guardConfigFileName]); ok {
		if data, err := os.ReadFile(p); err == nil {
			_ = json.Unmarshal([]byte(strings.TrimPrefix(string(data), "\ufeff")), &cfg)
		}
	}
	if domain := strings.TrimRight(strings.TrimSpace(os.Getenv("SERVER_DOMAIN")), "/"); domain != "" {
		cfg["backend_url"] = domain
		cfg["pac_url"] = domain + "/api/browser-ai/pac"
	} else if v, _ := cfg["backend_url"].(string); v == "" {
		return nil, errors.New("SERVER_DOMAIN is not set in .env")
	}
	if v := strings.TrimSpace(gatewayEnv("PROXY_ADDR")); v != "" {
		cfg["proxy_addr"] = v
	}
	if v := strings.TrimSpace(os.Getenv("PAC_HTTP_PORT")); v != "" {
		if n, err := strconv.Atoi(v); err == nil {
			cfg["pac_http_port"] = n
		} else {
			cfg["pac_http_port"] = v
		}
	}
	if secret := configuredGuardSecret(); secret != "" {
		cfg["guard_secret"] = secret
	} else if guardSecretRequired() {
		return nil, errors.New("GATEWAY_GUARD_SECRET is not set in .env — refusing to build a package without the Guard secret")
	}
	cfg["_comment"] = "Generated by the Gateway server (Browser AI → Setup → Build now) from .env"
	out, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}

// writeReleaseFileAtomic replaces path via a temp file in the same directory, so a download of the
// previous package never sees a half-written file.
func writeReleaseFileAtomic(path string, write func(io.Writer) error) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	bw := bufio.NewWriterSize(tmp, 1<<20)
	werr := write(bw)
	if werr == nil {
		werr = bw.Flush()
	}
	if cerr := tmp.Close(); werr == nil {
		werr = cerr
	}
	if werr == nil {
		_ = os.Chmod(tmpName, 0o644)
		werr = commitTempFile(tmpName, path)
	}
	if werr != nil {
		_ = os.Remove(tmpName)
	}
	return werr
}

// buildWindowsPackage writes release/Gateway_Guard_Windows.zip from the shipped Setup/portable
// EXEs plus a fresh config and the current helper files. Setup.exe installs a
// gateway_guard_config.json found next to it in place of the one it was compiled with.
func buildWindowsPackage(config []byte) (string, error) {
	setupPath, setupOK := findFirstExisting(browserAISetupCandidates()["Gateway_Guard_Setup.exe"])
	exePath, exeOK := findFirstExisting(browserAISetupCandidates()["Gateway_Guard.exe"])
	if !setupOK && !exeOK {
		return "", errors.New("no Windows Guard EXE on server — upload YP_Raksha_Setup.exe / YP_Raksha.exe to apps/browser-guard/release/ (tools/upload_guard_release.ps1 or the 1Panel file manager)")
	}
	releaseDir := filepath.Dir(setupPath)
	if !setupOK {
		releaseDir = filepath.Dir(exePath)
	}
	var assets []buildAsset
	if setupOK {
		assets = append(assets, buildAsset{name: "YP_Raksha_Setup.exe", path: setupPath})
	}
	if exeOK {
		assets = append(assets, buildAsset{name: "YP_Raksha.exe", path: exePath})
	}
	for _, name := range []string{"VERSION.txt"} {
		if p, ok := findFirstExisting(browserAISetupCandidates()[name]); ok {
			assets = append(assets, buildAsset{name: name, path: p})
		}
	}
	out := filepath.Join(releaseDir, "YP_Raksha_Windows.zip")
	err := writeReleaseFileAtomic(out, func(w io.Writer) error {
		zw := zip.NewWriter(w)
		for _, a := range assets {
			method := zip.Deflate
			if strings.HasSuffix(strings.ToLower(a.name), ".exe") {
				method = zip.Store
			}
			entry, err := zw.CreateHeader(&zip.FileHeader{Name: a.name, Method: method, Modified: time.Now()})
			if err != nil {
				return err
			}
			f, err := os.Open(a.path)
			if err != nil {
				return err
			}
			_, err = io.Copy(entry, f)
			f.Close()
			if err != nil {
				return err
			}
		}
		entry, err := zw.CreateHeader(&zip.FileHeader{Name: guardConfigFileName, Method: zip.Deflate, Modified: time.Now()})
		if err != nil {
			return err
		}
		if _, err := entry.Write(config); err != nil {
			return err
		}
		return zw.Close()
	})
	if err != nil {
		return "", err
	}
	// Clean up any legacy Gateway_Guard_Windows.zip
	gwOut := filepath.Join(releaseDir, "Gateway_Guard_Windows.zip")
	_ = os.Remove(gwOut)
	_ = writeReleaseFileAtomic(filepath.Join(releaseDir, guardConfigFileName), func(w io.Writer) error {
		_, err := w.Write(config)
		return err
	})
	return out, nil
}

// buildMacPackage rewrites release/YP_Raksha_macOS.zip with a fresh config.
func buildMacPackage(config []byte) (string, error) {
	macZipPath, ok := findFirstExisting(browserAISetupCandidates()["Gateway_Guard_macOS.zip"])
	if !ok {
		return "", errors.New("no macOS Guard package on server — upload YP_Raksha_macOS.zip to apps/browser-guard/release/ (tools/upload_guard_release.ps1 or the 1Panel file manager)")
	}
	releaseDir := filepath.Dir(macZipPath)
	ypMacZip := filepath.Join(releaseDir, "YP_Raksha_macOS.zip")
	gwMacZip := filepath.Join(releaseDir, "Gateway_Guard_macOS.zip")

	if err := writeReleaseFileAtomic(ypMacZip, func(w io.Writer) error {
		return writeMacZipWithHelpers(w, macZipPath, config)
	}); err != nil {
		return "", err
	}
	// Clean up any legacy Gateway_Guard_macOS.zip
	_ = os.Remove(gwMacZip)
	return ypMacZip, nil
}

// buildAndServeSetupPackage handles "Build now": refresh the package on the server, publish
// the latest Guard code bundle, save the ZIP as the new release, and stream it back.
func (h *BrowserAIHandler) buildAndServeSetupPackage(ctx *fasthttp.RequestCtx, platform string) {
	if !h.requireGuardAdmin(ctx, "Admin role required to build Guard packages") {
		return
	}
	isMac := platform == "mac" || platform == "macos" || platform == "darwin"
	if !isMac && platform != "windows" && platform != "win" {
		SendError(ctx, fasthttp.StatusBadRequest, "platform must be windows or mac for Build now")
		return
	}
	guardBuildMu.Lock()
	defer guardBuildMu.Unlock()
	started := time.Now()

	config, err := freshGuardConfig()
	if err != nil {
		SendError(ctx, fasthttp.StatusBadRequest, "Build failed: "+err.Error())
		return
	}
	var (
		zipPath, fileName, version string
	)
	if isMac {
		zipPath, err = buildMacPackage(config)
		fileName, version = "YP_Raksha_macOS.zip", readGuardMacReleaseVersion()
	} else {
		zipPath, err = buildWindowsPackage(config)
		fileName, version = "YP_Raksha_Windows.zip", readGuardReleaseVersion()
	}
	_, winOK := findFirstExisting(append(
		browserAISetupCandidates()["Gateway_Guard_Setup.exe"],
		browserAISetupCandidates()["Gateway_Guard.exe"]...,
	))
	_, macOK := findFirstExisting(browserAISetupCandidates()["Gateway_Guard_macOS.zip"])
	bundle, bundleMsg := publishProxyBundleSummary()
	resp := map[string]any{
		"mode":          "build-now",
		"version":       readGuardReleaseVersion(),
		"mac_version":   readGuardMacReleaseVersion(),
		"windows_ready": winOK && (isMac || err == nil),
		"macos_ready":   macOK && (!isMac || err == nil),
		"proxy_bundle":  bundle,
	}
	if err != nil {
		resp["message"] = fmt.Sprintf("Build now (%s) failed: %v", platform, err)
		h.recordRebuild(ctx, started, "failed", resp, "")
		SendError(ctx, fasthttp.StatusInternalServerError, resp["message"].(string))
		return
	}
	resp["message"] = fmt.Sprintf("Build now (%s): %s rebuilt with the current server config. %s", platform, fileName, bundleMsg)
	status := "success"
	if _, failed := bundle["error"]; failed {
		status = "failed"
	}
	h.recordRebuild(ctx, started, status, resp, "")

	f, err := os.Open(zipPath)
	if err != nil {
		SendError(ctx, fasthttp.StatusInternalServerError, "Build finished but the package could not be read: "+err.Error())
		return
	}
	ctx.SetStatusCode(fasthttp.StatusOK)
	ctx.SetContentType("application/zip")
	ctx.Response.Header.Set("Content-Disposition", `attachment; filename="`+fileName+`"`)
	if version != "" {
		setGuardVersionHeaders(ctx, version)
	}
	ctx.SetBodyStreamWriter(func(w *bufio.Writer) {
		defer f.Close()
		_, _ = io.Copy(w, f)
		_ = w.Flush()
	})
}
